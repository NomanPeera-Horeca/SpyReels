CREATE TABLE IF NOT EXISTS `ai_studio_creator_profiles` (
  `id` varchar(36) NOT NULL,
  `userId` int NOT NULL,
  `workspaceId` varchar(36) NOT NULL,
  `name` varchar(160) NOT NULL,
  `status` enum('draft','training','ready','failed') NOT NULL DEFAULT 'draft',
  `presenterStyle` enum('office','podcast','whiteboard','warehouse','studio','walking') NOT NULL DEFAULT 'office',
  `voiceProvider` enum('elevenlabs','none') NOT NULL DEFAULT 'none',
  `avatarProvider` enum('heygen','none') NOT NULL DEFAULT 'none',
  `voiceId` varchar(255) NULL,
  `avatarId` varchar(255) NULL,
  `trainingVideoKey` text NULL,
  `voiceSampleKey` text NULL,
  `performanceProfile` json NOT NULL,
  `providerMetadata` json NULL,
  `consentConfirmedAt` datetime NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_ai_studio_profiles_user` (`userId`),
  KEY `idx_ai_studio_profiles_workspace` (`workspaceId`)
);

CREATE TABLE IF NOT EXISTS `ai_studio_video_jobs` (
  `id` varchar(36) NOT NULL,
  `userId` int NOT NULL,
  `workspaceId` varchar(36) NOT NULL,
  `creatorProfileId` varchar(36) NOT NULL,
  `scriptId` varchar(64) NULL,
  `title` varchar(240) NOT NULL,
  `status` enum('queued','directing','generating_voice','generating_presenter','collecting_broll','composing','quality_check','completed','failed','cancelled') NOT NULL DEFAULT 'queued',
  `progress` int NOT NULL DEFAULT 0,
  `currentStep` varchar(120) NOT NULL DEFAULT 'Queued',
  `aspectRatio` varchar(8) NOT NULL DEFAULT '9:16',
  `inputPayload` json NOT NULL,
  `outputUrl` text NULL,
  `outputKey` text NULL,
  `thumbnailUrl` text NULL,
  `errorMessage` text NULL,
  `startedAt` datetime NULL,
  `completedAt` datetime NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_ai_studio_jobs_user` (`userId`),
  KEY `idx_ai_studio_jobs_workspace` (`workspaceId`),
  KEY `idx_ai_studio_jobs_status` (`status`),
  KEY `idx_ai_studio_jobs_profile` (`creatorProfileId`)
);

CREATE TABLE IF NOT EXISTS `ai_studio_scenes` (
  `id` varchar(64) NOT NULL,
  `jobId` varchar(36) NOT NULL,
  `sceneOrder` int NOT NULL,
  `sceneType` enum('presenter','broll','graphic') NOT NULL,
  `status` enum('queued','processing','completed','failed') NOT NULL DEFAULT 'queued',
  `direction` json NOT NULL,
  `voiceUrl` text NULL,
  `presenterUrl` text NULL,
  `brollUrl` text NULL,
  `composedUrl` text NULL,
  `qualityScore` int NULL,
  `errorMessage` text NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_ai_studio_scenes_job` (`jobId`),
  UNIQUE KEY `uq_ai_studio_scene_order` (`jobId`,`sceneOrder`)
);

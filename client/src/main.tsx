function decodeBase64UrlUtf8(value: string): string | null {
  try {
    const normalized = value.replace(/-/g, "+").replace(/_/g, "/");
    const padded = normalized.padEnd(Math.ceil(normalized.length / 4) * 4, "=");
    const binary = window.atob(padded);
    const bytes = Uint8Array.from(binary, (char) => char.charCodeAt(0));
    return new TextDecoder().decode(bytes);
  } catch {
    return null;
  }
}

/**
 * Last-resort recovery for an old/stale service worker that serves index.html
 * for the OAuth login bridge before the new Workbox denylist takes effect.
 * The bridge's `request` payload is generated by our server and must resolve
 * only to the real same-origin OAuth authorize API route.
 */
if (typeof window !== "undefined" && window.location.pathname === oauthContinuePath) {
  const encoded = new URLSearchParams(window.location.search).get("request") || "";
  const target = decodeBase64UrlUtf8(encoded);
  if (
    target === oauthAuthorizePath ||
    target?.startsWith(`${oauthAuthorizePath}?`)
  ) {
    window.location.replace(target);
  }
}

